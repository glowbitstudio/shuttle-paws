# Usage: venue-thumbs.py <port>  -- renders every venue in a real match (menus and HUD hidden), shrinks it to a small JPEG and writes
# venue_art.js: window.VENUE_ART = { id: 'data:image/jpeg;base64,...' }, the pictures behind the venue cards. Also saves a contact sheet
# (venue_art_sheet.png, not tracked) to look at. ONE headless browser, one page per venue.
from pathlib import Path
import sys,io,json,base64
from playwright.sync_api import sync_playwright
from PIL import Image
ROOT=Path(__file__).resolve().parents[1];PORT=sys.argv[1];W,H=288,162
HOOK="window.__vn=()=>S.VENUES.map(v=>v.id);\n"
art={};tiles=[];errs=[]
with sync_playwright() as p:
    b=p.chromium.launch(headless=True,args=['--use-angle=swiftshader']);ids=None;i=0
    while ids is None or i<len(ids):
        ctx=b.new_context(viewport={'width':768,'height':432});pg=ctx.new_page();pg.set_default_timeout(120000)
        ctx.add_init_script("localStorage.setItem('sp.settings',JSON.stringify({helpN:99,gfx:1,gfxV:1,vol:0,cam:'high'}));localStorage.setItem('sp.profile',JSON.stringify({name:'Thu',char:'cat',id:null,secret:null,named:true}));")
        pg.on('pageerror',lambda e:errs.append(str(e)[:200]));pg.route('https://**/*',lambda r:r.abort())
        pg.route('**/game.js',lambda r:r.fulfill(status=200,content_type='application/javascript',body=(ROOT/'game.js').read_bytes().decode('utf-8').replace('window.__spDebug = {',HOOK+'window.__spDebug = {',1)))
        pg.goto(f'http://127.0.0.1:{PORT}/',wait_until='domcontentloaded');pg.wait_for_function('typeof __spDebug === "object"');pg.wait_for_timeout(800)
        if ids is None: ids=pg.evaluate('()=>__vn()')
        pg.evaluate("(v)=>__spDebug.startLocal({diff:1,mode:'1v1',points:11,venue:v,anyVenue:true})",i);pg.wait_for_timeout(4200)
        pg.add_style_tag(content='body > *:not(canvas){visibility:hidden!important}');pg.wait_for_timeout(300)
        im=Image.open(io.BytesIO(pg.screenshot())).convert('RGB').resize((W,H),Image.LANCZOS);buf=io.BytesIO();im.save(buf,'JPEG',quality=60,optimize=True)
        art[ids[i]]='data:image/jpeg;base64,'+base64.b64encode(buf.getvalue()).decode('ascii');tiles.append(im);ctx.close();i+=1
    b.close()
(ROOT/'venue_art.js').write_text('// Generated by tests/venue-thumbs.py: a small picture of every venue for the venue cards.\nwindow.VENUE_ART = '+json.dumps(art,separators=(',',':'))+';\n',encoding='utf-8')
cols=5;rows=(len(tiles)+cols-1)//cols;sheet=Image.new('RGB',(cols*W,rows*H),'white')
for k,t in enumerate(tiles): sheet.paste(t,((k%cols)*W,(k//cols)*H))
sheet.save(ROOT/'venue_art_sheet.png');print(json.dumps({'venues':len(art),'bytes':(ROOT/'venue_art.js').stat().st_size,'errors':errs}))
